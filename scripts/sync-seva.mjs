/* The serverless function must be self-contained: Vercel's runtime resolves
   api/ imports at /var/task/api/ under strict ESM, so a reach into ../src does
   not survive deployment and extensionless TS imports do not either. This
   script transpiles src/content/seva.ts to plain ESM JavaScript at
   api/_seva-data.js (underscore = not an endpoint) so the function can import
   it with an explicit extension Node resolves at runtime. Run before every
   build so the copies cannot drift. */

import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { transformSync } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'src/content/seva.ts'), 'utf8');

const { code } = transformSync(src, { loader: 'ts', format: 'esm', target: 'es2022' });
const out = '/* AUTO-GENERATED by scripts/sync-seva.mjs from src/content/seva.ts — do not edit. */\n' + code;
writeFileSync(join(root, 'api/_seva-data.js'), out);
console.log('sync-seva: api/_seva-data.js written (' + out.length + ' chars)');

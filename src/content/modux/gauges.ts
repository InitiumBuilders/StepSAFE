/** One gauge per calendar day, the same one for everyone. */
export function gaugeOfTheDay(now = new Date()): ModuxGauge {
  const day = Math.floor(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) / 86400000);
  return GAUGES[day % GAUGES.length];
}
